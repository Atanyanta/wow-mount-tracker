// Validates data/farmables.json against data/mounts.json and regenerates
// docs/farmables-review.md - a grouped, human-reviewable table of every
// mount on the Dailies tab (with the raw source text from mounts.json next to
// each row so it can be eyeballed against the curated classification).
//
// Usage: npm run check:farmables   (exits 1 if any id/name problem is found)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mounts = JSON.parse(readFileSync(join(root, "data", "mounts.json"), "utf8"));
const farmables = JSON.parse(readFileSync(join(root, "data", "farmables.json"), "utf8"));
const byId = new Map(mounts.map((m) => [m.id, m]));

const CADENCES = new Set(["daily", "weekly"]);
const CONFIDENCE = new Set(["high", "medium", "low"]);
const problems = [];
const seen = new Map(); // mount id -> activity id
const activityIds = new Set();

function check(cond, msg) {
  if (!cond) problems.push(msg);
}

for (const group of farmables.groups) {
  check(CADENCES.has(group.cadence), `group ${group.id}: bad cadence "${group.cadence}"`);
  for (const act of group.activities) {
    check(!activityIds.has(act.id), `duplicate activity id "${act.id}"`);
    activityIds.add(act.id);
    check(CONFIDENCE.has(act.confidence), `activity ${act.id}: bad confidence "${act.confidence}"`);
    check(act.mounts?.length > 0, `activity ${act.id}: no mounts`);
    for (const fm of act.mounts) {
      const real = byId.get(fm.id);
      if (!real) {
        problems.push(`activity ${act.id}: mount id ${fm.id} ("${fm.name}") not in mounts.json`);
        continue;
      }
      check(real.name === fm.name, `activity ${act.id}: id ${fm.id} is "${real.name}" in mounts.json, not "${fm.name}"`);
      check(!seen.has(fm.id), `mount id ${fm.id} ("${fm.name}") appears in both "${seen.get(fm.id)}" and "${act.id}"`);
      seen.set(fm.id, act.id);
      if (fm.confidence) check(CONFIDENCE.has(fm.confidence), `activity ${act.id}: mount ${fm.id} bad confidence`);
    }
  }
}
for (const ex of farmables.excluded ?? []) {
  for (const fm of ex.mounts) {
    const real = byId.get(fm.id);
    check(real, `excluded: id ${fm.id} not in mounts.json`);
    if (real) check(real.name === fm.name, `excluded: id ${fm.id} is "${real.name}", not "${fm.name}"`);
    check(!seen.has(fm.id), `excluded mount ${fm.id} ("${fm.name}") is also included in "${seen.get(fm.id)}"`);
  }
}

// ---- review document ----
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const lines = [];
lines.push("# Farmable mounts - review sheet");
lines.push("");
lines.push("_Generated by `npm run check:farmables` from `data/farmables.json`. Do not edit by hand - edit the JSON and rerun._");
lines.push("");
let total = 0;
const counts = { high: 0, medium: 0, low: 0 };
for (const g of farmables.groups) for (const a of g.activities) for (const m of a.mounts) { total++; counts[m.confidence ?? a.confidence]++; }
lines.push(`**${total} mounts** in ${activityIds.size} activities. Confidence: ${counts.high} high, ${counts.medium} medium, ${counts.low} low.`);
lines.push("");
lines.push("Confidence key: **high** = confirmed by Wowhead's daily/weekly guide or in-data notes; **medium** = rule inferred (see note); **low** = unverified, please check in game.");
lines.push("");

for (const group of farmables.groups) {
  lines.push(`## ${group.title}`);
  lines.push("");
  lines.push(`Cadence: **${group.cadence}**${group.eventOnly ? " (event-only)" : ""}`);
  lines.push("");
  for (const act of group.activities) {
    lines.push(`### ${act.name}`);
    lines.push(`${act.zone} - ${act.expansion} - ${act.difficulty} - confidence: **${act.confidence}**`);
    if (act.note) lines.push(`> ${esc(act.note)}`);
    lines.push("");
    lines.push("| Mount | ID | Boss | Difficulty | Conf. | Source text in mounts.json |");
    lines.push("|---|---|---|---|---|---|");
    for (const fm of act.mounts) {
      const real = byId.get(fm.id);
      const src = real?.source ? esc(real.source).slice(0, 110) : "_(none)_";
      lines.push(`| ${esc(fm.name)} | ${fm.id} | ${esc(fm.boss)} | ${esc(fm.difficulty ?? "")} | ${fm.confidence ?? act.confidence} | ${src} |`);
    }
    lines.push("");
  }
}

lines.push("## Considered but excluded");
lines.push("");
for (const ex of farmables.excluded ?? []) {
  lines.push(`- **${esc(ex.reason)}**${ex.mounts.length ? ": " + ex.mounts.map((m) => `${esc(m.name)} (${m.id})`).join(", ") : ""}`);
}
lines.push("");

mkdirSync(join(root, "docs"), { recursive: true });
writeFileSync(join(root, "docs", "farmables-review.md"), lines.join("\n"));

if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const p of problems) console.error(" - " + p);
  process.exit(1);
}
console.log(`farmables.json OK: ${total} mounts / ${activityIds.size} activities. Wrote docs/farmables-review.md`);
